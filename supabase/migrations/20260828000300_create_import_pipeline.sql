create extension if not exists pgcrypto;

create table if not exists core.upload_batch (
  batch_id uuid primary key default gen_random_uuid(),
  file_name text not null,
  import_type text not null check (import_type in (
    'usage_history', 'inventory', 'item_master', 'supplier_master',
    'purchase_order', 'goods_receipt', 'sales_order', 'business_event'
  )),
  import_mode text not null check (import_mode in ('append', 'upsert', 'replace')),
  total_rows integer not null default 0 check (total_rows >= 0),
  success_rows integer not null default 0 check (success_rows >= 0),
  warning_rows integer not null default 0 check (warning_rows >= 0),
  error_rows integer not null default 0 check (error_rows >= 0),
  status text not null default 'STAGED' check (status in (
    'STAGED', 'VALIDATING', 'VALIDATED', 'IMPORTING',
    'IMPORTED', 'FAILED', 'ROLLED_BACK'
  )),
  uploaded_by uuid not null references auth.users(id) on delete restrict,
  uploaded_at timestamptz not null default now(),
  imported_at timestamptz,
  forecast_stale boolean not null default false,
  data_snapshot_at timestamptz,
  replace_confirmed_at timestamptz,
  replace_confirmed_by uuid references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (success_rows + warning_rows + error_rows <= total_rows)
);

create table if not exists core.import_staging (
  batch_id uuid not null references core.upload_batch(batch_id) on delete cascade,
  row_number integer not null check (row_number > 0),
  source_data jsonb not null,
  normalized_data jsonb,
  validation_status text not null default 'PENDING'
    check (validation_status in ('PENDING', 'SUCCESS', 'WARNING', 'ERROR')),
  staged_at timestamptz not null default now(),
  primary key (batch_id, row_number)
);

create table if not exists core.validation_error (
  id bigint generated by default as identity primary key,
  batch_id uuid not null references core.upload_batch(batch_id) on delete cascade,
  row_number integer not null check (row_number > 0),
  field_name text not null,
  error_code text not null,
  error_message text not null,
  severity text not null check (severity in ('WARNING', 'ERROR')),
  original_value text,
  created_at timestamptz not null default now(),
  unique (batch_id, row_number, field_name, error_code)
);

create table if not exists core.column_mapping (
  import_type text not null check (import_type in (
    'usage_history', 'inventory', 'item_master', 'supplier_master',
    'purchase_order', 'goods_receipt', 'sales_order', 'business_event'
  )),
  source_header text not null,
  target_column text not null,
  confidence numeric(5,4),
  confirmed boolean not null default false,
  updated_by uuid references auth.users(id) on delete restrict,
  updated_at timestamptz not null default now(),
  primary key (import_type, source_header),
  check (confidence is null or confidence between 0 and 1)
);

create table if not exists core.import_backup (
  id bigint generated by default as identity primary key,
  batch_id uuid not null references core.upload_batch(batch_id) on delete cascade,
  import_type text not null,
  record_key text not null,
  target_table text not null,
  before_data jsonb,
  action text not null check (action in ('INSERTED', 'UPDATED', 'DELETED')),
  restored_at timestamptz,
  created_at timestamptz not null default now(),
  unique (batch_id, target_table, record_key)
);

create index if not exists upload_batch_status_idx
on core.upload_batch(status, uploaded_at desc);

create index if not exists import_staging_batch_status_idx
on core.import_staging(batch_id, validation_status);

create index if not exists validation_error_batch_idx
on core.validation_error(batch_id, severity, row_number);

create index if not exists import_backup_batch_idx
on core.import_backup(batch_id, target_table, record_key);

