create or replace function core.import_approved_batch(target_batch_id uuid)
returns jsonb
language plpgsql
volatile
security definer
set search_path = pg_catalog, core, raw
as $$
declare
  actor_id uuid := (select auth.uid());
  batch_row core.upload_batch;
  stage_row record;
  before_data jsonb;
  table_name text;
  key_table_expr text;
  key_json_expr text;
  insert_columns text;
  select_columns text;
  record_key text;
  imported_count integer := 0;
begin
  if actor_id is null or not core.is_admin() then
    raise exception using errcode = '42501', message = '관리자 권한이 필요합니다.';
  end if;

  select * into batch_row
  from core.upload_batch
  where batch_id = target_batch_id
  for update;

  if not found then
    raise exception using errcode = 'P0002', message = '업로드 batch를 찾을 수 없습니다.';
  end if;

  if batch_row.status <> 'VALIDATED' or batch_row.error_rows > 0 then
    raise exception using errcode = '42501', message = '검증이 완료된 오류 없는 batch만 Import할 수 있습니다.';
  end if;

  if batch_row.import_mode = 'replace' and batch_row.replace_confirmed_at is null then
    raise exception using errcode = '42501', message = 'replace Import는 사용자 확인이 필요합니다.';
  end if;

  if batch_row.import_type = 'usage_history' then
    table_name := 'usage_history';
    key_table_expr := 'coalesce(t.usage_id, '''')';
    key_json_expr := 'coalesce($1->>''usage_id'', '''')';
    insert_columns := 'usage_id, item_id, use_date, qty, warehouse, note';
    select_columns := 'r.usage_id, r.item_id, r.use_date, r.qty, r.warehouse, r.note';
  elsif batch_row.import_type = 'inventory' then
    table_name := 'inventory';
    key_table_expr := 'coalesce(t."품목코드", '''') || ''|'' || coalesce(t."창고", '''') || ''|'' || coalesce(t."기준일자", '''')';
    key_json_expr := 'coalesce($1->>''품목코드'', '''') || ''|'' || coalesce($1->>''창고'', '''') || ''|'' || coalesce($1->>''기준일자'', '''')';
    insert_columns := '"품목코드", "창고", "현재고", "기준일자", "안전재고"';
    select_columns := 'r."품목코드", r."창고", r."현재고", r."기준일자", r."안전재고"';
  elsif batch_row.import_type = 'item_master' then
    table_name := 'item_master';
    key_table_expr := 'coalesce(t."품목코드", '''')';
    key_json_expr := 'coalesce($1->>''품목코드'', '''')';
    insert_columns := '"품목코드", "품목명", "품목구분", "단위", "표준단가", "사용여부", supplier_id';
    select_columns := 'r."품목코드", r."품목명", r."품목구분", r."단위", r."표준단가", r."사용여부", r.supplier_id';
  elsif batch_row.import_type = 'supplier_master' then
    table_name := 'supplier_master';
    key_table_expr := 'coalesce(t."공급업체코드", '''')';
    key_json_expr := 'coalesce($1->>''공급업체코드'', '''')';
    insert_columns := '"공급업체코드", "공급업체명", "국가", "표준리드타임(일)", "담당자", "사용여부"';
    select_columns := 'r."공급업체코드", r."공급업체명", r."국가", r."표준리드타임(일)", r."담당자", r."사용여부"';
  elsif batch_row.import_type = 'purchase_order' then
    table_name := 'purchase_order';
    key_table_expr := 'coalesce(t."발주번호", '''')';
    key_json_expr := 'coalesce($1->>''발주번호'', '''')';
    insert_columns := '"발주번호", "발주일", "공급업체", "품목코드", "발주수량", "단가", "납기예정일", "발주담당"';
    select_columns := 'r."발주번호", r."발주일", r."공급업체", r."품목코드", r."발주수량", r."단가", r."납기예정일", r."발주담당"';
  elsif batch_row.import_type = 'goods_receipt' then
    table_name := 'goods_receipt';
    key_table_expr := 'coalesce(t."입고번호", '''')';
    key_json_expr := 'coalesce($1->>''입고번호'', '''')';
    insert_columns := '"입고번호", "발주번호", "품목코드", "입고수량", "입고일", "입고창고"';
    select_columns := 'r."입고번호", r."발주번호", r."품목코드", r."입고수량", r."입고일", r."입고창고"';
  elsif batch_row.import_type = 'sales_order' then
    table_name := 'sales_order';
    key_table_expr := 'coalesce(t.sales_order_id, '''')';
    key_json_expr := 'coalesce($1->>''sales_order_id'', '''')';
    insert_columns := 'sales_order_id, order_date, customer_id, item_id, quantity, need_date, status';
    select_columns := 'r.sales_order_id, r.order_date, r.customer_id, r.item_id, r.quantity, r.need_date, r.status';
  elsif batch_row.import_type = 'business_event' then
    table_name := 'business_event';
    key_table_expr := 'coalesce(t.event_id, '''')';
    key_json_expr := 'coalesce($1->>''event_id'', '''')';
    insert_columns := 'event_id, event_type, event_date, item_id, supplier_id, event_name, impact_factor, note';
    select_columns := 'r.event_id, r.event_type, r.event_date, r.item_id, r.supplier_id, r.event_name, r.impact_factor, r.note';
  else
    raise exception using errcode = '22023', message = '지원하지 않는 Import Type입니다.';
  end if;

  if batch_row.import_mode = 'replace' then
    execute format(
      'insert into core.import_backup (batch_id, import_type, record_key, target_table, before_data, action)
       select $1, $2, %s, $3, to_jsonb(t), ''DELETED'' from raw.%I t
       on conflict (batch_id, target_table, record_key) do nothing',
      key_table_expr, table_name
    ) using target_batch_id, batch_row.import_type, table_name;
    execute format('delete from raw.%I', table_name);
  end if;

  for stage_row in
    select normalized_data
    from core.import_staging
    where batch_id = target_batch_id
      and validation_status in ('SUCCESS', 'WARNING')
    order by row_number
  loop
    execute format('select %s', key_json_expr)
      into record_key
      using stage_row.normalized_data;

    if batch_row.import_mode = 'upsert' then
      execute format('select to_jsonb(t) from raw.%I t where %s = %s', table_name, key_table_expr, key_json_expr)
        into before_data
        using stage_row.normalized_data;
      if before_data is not null then
        insert into core.import_backup (batch_id, import_type, record_key, target_table, before_data, action)
        values (target_batch_id, batch_row.import_type, record_key, table_name, before_data, 'UPDATED')
        on conflict (batch_id, target_table, record_key) do nothing;
        execute format('delete from raw.%I t where %s = %s', table_name, key_table_expr, key_json_expr)
          using stage_row.normalized_data;
      end if;
    end if;

    execute format(
      'insert into raw.%I (%s, batch_id, source_type, loaded_at, source_record_id)
       select %s, $2, ''FILE_UPLOAD'', now(), $3
       from jsonb_populate_record(null::raw.%I, $1) r',
      table_name, insert_columns, select_columns, table_name
    ) using stage_row.normalized_data, target_batch_id, record_key;
    imported_count := imported_count + 1;
  end loop;

  update core.upload_batch
  set status = 'IMPORTED',
      imported_at = now(),
      data_snapshot_at = now(),
      forecast_stale = (batch_row.import_type in ('usage_history', 'sales_order')),
      updated_at = now()
  where batch_id = target_batch_id;

  return jsonb_build_object('batch_id', target_batch_id, 'imported_rows', imported_count, 'status', 'IMPORTED');
end;
$$;

create or replace function core.rollback_batch(target_batch_id uuid)
returns jsonb
language plpgsql
volatile
security definer
set search_path = pg_catalog, core, raw
as $$
declare
  actor_id uuid := (select auth.uid());
  batch_row core.upload_batch;
  backup_row record;
  table_name text;
  restored_count integer := 0;
begin
  if actor_id is null or not core.is_admin() then
    raise exception using errcode = '42501', message = '관리자 권한이 필요합니다.';
  end if;

  select * into batch_row
  from core.upload_batch
  where batch_id = target_batch_id
  for update;

  if not found then
    raise exception using errcode = 'P0002', message = '업로드 batch를 찾을 수 없습니다.';
  end if;
  if batch_row.status <> 'IMPORTED' then
    raise exception using errcode = '42501', message = 'Import 완료 상태의 batch만 rollback할 수 있습니다.';
  end if;

  table_name := batch_row.import_type;
  execute format('delete from raw.%I where batch_id = $1', table_name) using target_batch_id;

  for backup_row in
    select target_table, before_data
    from core.import_backup
    where batch_id = target_batch_id
      and before_data is not null
      and restored_at is null
    order by id
  loop
    execute format(
      'insert into raw.%I select r.* from jsonb_populate_record(null::raw.%I, $1) r',
      backup_row.target_table, backup_row.target_table
    ) using backup_row.before_data;
    update core.import_backup
    set restored_at = now()
    where batch_id = target_batch_id
      and target_table = backup_row.target_table
      and before_data = backup_row.before_data;
    restored_count := restored_count + 1;
  end loop;

  update core.upload_batch
  set status = 'ROLLED_BACK', updated_at = now()
  where batch_id = target_batch_id;

  return jsonb_build_object('batch_id', target_batch_id, 'restored_rows', restored_count, 'status', 'ROLLED_BACK');
end;
$$;

grant execute on function core.import_approved_batch(uuid) to authenticated;
grant execute on function core.rollback_batch(uuid) to authenticated;
revoke all on function core.import_approved_batch(uuid) from public, anon;
revoke all on function core.rollback_batch(uuid) from public, anon;
