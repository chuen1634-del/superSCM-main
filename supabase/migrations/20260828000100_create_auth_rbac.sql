create policy app_user_select_own_or_admin on core.app_user for select to authenticated using ((select auth.uid()) = user_id or (select core.is_admin()));
drop policy if exists app_user_admin_update on core.app_user;
create policy app_user_admin_update on core.app_user for update to authenticated using ((select core.is_admin())) with check ((select core.is_admin()));
drop policy if exists audit_log_admin_select on core.audit_log;
create policy audit_log_admin_select on core.audit_log for select to authenticated using ((select core.is_admin()));
drop policy if exists leadtime_plan_authenticated_select on core.leadtime_plan;
