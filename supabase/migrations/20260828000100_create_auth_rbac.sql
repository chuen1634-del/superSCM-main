create schema if not exists core;

create table if not exists core.app_user (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  name text not null default '',
  department text not null default '',
  role text not null default 'USER' check (role in ('ADMIN', 'USER')),
  active boolean not null default true,
  last_login_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists core.audit_log (
  id bigint generated by default as identity primary key,
  actor uuid not null references auth.users(id) on delete restrict,
  action text not null,
  target_type text not null,
  target_id text not null,
  before jsonb,
  after jsonb,
  at timestamptz not null default now()
);

create index if not exists app_user_role_active_idx on core.app_user(role, active);
create index if not exists audit_log_target_idx on core.audit_log(target_type, target_id, at desc);

create or replace function core.set_app_user_updated_at()
returns trigger language plpgsql security invoker set search_path = pg_catalog as $$
begin new.updated_at = now(); return new; end;
$$;

drop trigger if exists app_user_set_updated_at on core.app_user;
create trigger app_user_set_updated_at before update on core.app_user for each row execute function core.set_app_user_updated_at();

create or replace function core.handle_new_auth_user()
returns trigger language plpgsql security definer set search_path = pg_catalog, core as $$
begin
  insert into core.app_user (user_id, email, name, department)
  values (new.id, coalesce(new.email, ''), coalesce(new.raw_user_meta_data ->> 'name', ''), coalesce(new.raw_user_meta_data ->> 'department', ''))
  on conflict (user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute function core.handle_new_auth_user();

create or replace function core.is_admin()
returns boolean language sql stable security definer set search_path = pg_catalog, core as $$
  select exists (select 1 from core.app_user where user_id = (select auth.uid()) and role = 'ADMIN' and active = true);
$$;

create or replace function core.admin_update_user(target_user_id uuid, next_role text, next_active boolean)
returns core.app_user language plpgsql volatile security definer set search_path = pg_catalog, core as $$
declare
  actor_id uuid := (select auth.uid());
  before_row core.app_user;
  after_row core.app_user;
begin
  if actor_id is null or not core.is_admin() then raise exception using errcode = '42501', message = '관리자 권한이 필요합니다.'; end if;
  if next_role not in ('ADMIN', 'USER') then raise exception using errcode = '22023', message = '올바르지 않은 role입니다.'; end if;
  if target_user_id = actor_id and (next_role <> 'ADMIN' or next_active = false) then raise exception using errcode = '42501', message = '자신의 관리자 권한과 활성 상태는 변경할 수 없습니다.'; end if;
  select * into before_row from core.app_user where user_id = target_user_id for update;
  if not found then raise exception using errcode = 'P0002', message = '사용자를 찾을 수 없습니다.'; end if;
  update core.app_user set role = next_role, active = next_active where user_id = target_user_id returning * into after_row;
  insert into core.audit_log (actor, action, target_type, target_id, before, after)
  values (actor_id, case when before_row.role <> after_row.role then 'USER_ROLE_CHANGED' else 'USER_ACTIVE_CHANGED' end, 'app_user', target_user_id::text, to_jsonb(before_row), to_jsonb(after_row));
  return after_row;
end;
$$;

create or replace function core.record_login()
returns void language plpgsql volatile security definer set search_path = pg_catalog, core as $$
begin
  update core.app_user set last_login_at = now() where user_id = (select auth.uid()) and active = true;
end;
$$;

